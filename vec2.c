#include "vec2.h"
/**
 * Создает и инициализирует новый экземпляр двухкомпонентного вектора.
 *
 * @param x Значение координаты Х.
 * @param y Значение координаты Y.
 *
 * @return vec2_t Новый сформированный вектор с заданными координатами.
 */
vec2_t make_vec2(int x, int y)
{
    vec2_t v;
    v.x = x;
    v.y = y;
    return v;
}

/**
 * Функция доступа для получения координаты Х вектора.
 *
 * @param v Вектор, координату которого необходимо получить. 
 *
 * @return int Значение проекции вектора на ось Х.
 */
int vec2_x (vec2_t v)
{
    return v.x;
}

/**
 * Функция доступа для получения координаты Y вектора.
 *
 * @param v Вектор, координату которого необходимо получить. 
 *
 * @return int Значение проекции вектора на ось Y.
 */
int vec2_y (vec2_t v)
{
    return v.y;
}

/**
 * Функция вычисляет сумму двух векторов.
 *
 * @param v1 Первый вектор(первое слагаемое).
 * @param v2 Второй вектор(второе слагаемое).
 *
 * @return vec2_t Новый результирующий вектор суммы.
 */
vec2_t vec2_add(vec2_t v1, vec2_t v2)
{
    return make_vec2(v1.x + v2.x, v1.y + v2.y);
}

/**
 * Функция вычисляет разность двух векторов.
 *
 * @param v1 Вектор-уменьшаемое.
 * @param v2 Вектор-вычитаемое.
 *
 * @return vec2_t Новый результирующий вектор разности.
 */
vec2_t vec2_sub(vec2_t v1, vec2_t v2)
{
    return make_vec2(v1.x - v2.x, v1.y - v2.y);
}

/**
 * Функция выполняет умножение вектора на число (скалярное масштабирование).
 *
 * @param v Исходный масштабируемый вектор.
 * @param scalar Скалярный множитель (число).
 *
 * @return vec2_t Новый вектор, масштабированный на указанный скаляр.
 */
vec2_t vec2_scale(vec2_t v, int scalar)
{
    return make_vec2(v.x * scalar, v.y * scalar);
}
